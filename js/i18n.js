/** Look up a string, filling {placeholders}. Falls back to Hebrew, then the key. */
export function t(lang, key, vars) {
  const table = UI[lang] || UI.he;
  let text = table[key];
  if (text === undefined) text = UI.he[key];
  if (text === undefined) return key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, name) => (vars[name] === undefined ? m : vars[name]));
}
